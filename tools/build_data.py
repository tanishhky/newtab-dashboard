"""Generate js/data.js from the private application log and deadline list.

Reads Applications/applications.csv (free-text status column) and
data/deadlines.json, normalizes both, and writes an ES module the new tab
page imports. The output holds personal data, so it is gitignored.

Usage:
    python3 tools/build_data.py [--csv PATH] [--deadlines PATH] [--out PATH]
"""

import argparse
import csv
import json
import re
from datetime import date, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_CSV = Path.home() / "Documents/SecondBrain/Applications/applications.csv"
DEFAULT_DEADLINES = ROOT / "data/deadlines.json"
DEFAULT_OUT = ROOT / "js/data.js"


def bucket(status: str) -> str:
    """Map a free-text status onto one of a fixed set of pipeline buckets."""
    s = status.strip().lower()
    if s.startswith("rejected"):
        return "rejected"
    if s.startswith("selected") or s.startswith("offer"):
        return "selected"
    if s.startswith("assessment"):
        return "assessment"
    if s.startswith("applied"):
        return "applied"
    if s.startswith("resume ready"):
        return "ready"
    if s.startswith(("skipped", "closed")):
        return "closed"
    return "other"


def short_status(status: str) -> str:
    """Keep the leading clause only: 'Applied 2026-09-30 (Greenhouse ...)' -> 'Applied 2026-09-30'."""
    s = status.replace("\u2014", "-").replace("\u2013", "-")
    return re.split(r"\s[\(\-]", s.strip(), maxsplit=1)[0].strip()


def parse_log_date(raw: str) -> str | None:
    """Parse the CSV's m/d/yy dates into ISO yyyy-mm-dd, or None if unparseable."""
    try:
        return datetime.strptime(raw.strip(), "%m/%d/%y").date().isoformat()
    except ValueError:
        return None


def load_applications(csv_path: Path) -> list[dict]:
    rows = []
    with csv_path.open(newline="", encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            company = (row.get("company") or "").strip()
            if not company:
                continue
            status = row.get("status") or ""
            rows.append(
                {
                    "company": company,
                    "role": (row.get("role") or "").strip(),
                    "date": parse_log_date(row.get("date") or ""),
                    "bucket": bucket(status),
                    "status": short_status(status),
                }
            )
    # Newest first; undated rows sink to the bottom.
    rows.sort(key=lambda r: r["date"] or "", reverse=True)
    return rows


def load_deadlines(path: Path) -> list[dict]:
    if not path.exists():
        return []
    items = json.loads(path.read_text(encoding="utf-8"))
    for item in items:
        date.fromisoformat(item["date"])  # fail loudly on a malformed date
    return sorted(items, key=lambda d: (d["date"], d.get("time", "")))


def render(applications: list[dict], deadlines: list[dict]) -> str:
    payload = json.dumps(
        {"applications": applications, "deadlines": deadlines},
        indent=2,
        ensure_ascii=False,
    )
    return (
        "// Generated by tools/build_data.py. Personal data; do not commit.\n"
        f"export const DATA = {payload};\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--csv", type=Path, default=DEFAULT_CSV)
    parser.add_argument("--deadlines", type=Path, default=DEFAULT_DEADLINES)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()

    apps = load_applications(args.csv)
    deadlines = load_deadlines(args.deadlines)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(apps, deadlines), encoding="utf-8")
    print(f"wrote {args.out}: {len(apps)} applications, {len(deadlines)} deadlines")


if __name__ == "__main__":
    main()
